"""Date helpers give the same answers as vournalOS's DateService (golden/dates.json,
regenerated by golden/dates_golden.mjs). Any difference is a Python bug."""

import json
import pathlib
import unittest
from datetime import datetime, timedelta, timezone
from unittest.mock import patch

GOLDEN = json.loads((pathlib.Path(__file__).parent / "golden" / "dates.json").read_text())


def _arg(value, method):
    if isinstance(value, str) and value.endswith("Z") and "T" in value and method != "parseDateOnly":
        return datetime.fromisoformat(value.replace("Z", "+00:00"))
    return value


def _out(value):
    from app.os.common.serialize import to_json

    if isinstance(value, dict):
        return {k: to_json(v) for k, v in value.items()}
    return to_json(value)


class Golden(unittest.TestCase):
    def test_every_golden_case(self):
        from app.os.common import dates

        names = {
            "startOfDay": "start_of_day", "endOfDay": "end_of_day", "startOfWeek": "start_of_week",
            "endOfWeek": "end_of_week", "startOfMonth": "start_of_month", "endOfMonth": "end_of_month",
            "startOfYear": "start_of_year", "endOfYear": "end_of_year", "range": "range",
            "addDays": "add_days", "localDateString": "local_date_string", "toDateOnly": "to_date_only",
            "parseDateOnly": "parse_date_only", "diffDays": "diff_days", "diffCalendarDays": "diff_calendar_days",
        }
        for case in GOLDEN:
            with self.subTest(case["id"], method=case["method"], args=case["args"]):
                fn = getattr(dates, names[case["method"]])
                self.assertEqual(_out(fn(*[_arg(a, case["method"]) for a in case["args"]])), case["result"])


class TodayRelative(unittest.TestCase):
    def test_next_anniversary_and_days_until(self):
        from app.os.common import dates

        now = datetime(2026, 11, 3, 22, 30, tzinfo=timezone.utc)  # 00:30 on Nov 4 in Beirut (UTC+2)
        with patch.object(dates, "_now", return_value=now):
            self.assertEqual(dates.today_date_only("Asia/Beirut"), datetime(2026, 11, 4, tzinfo=timezone.utc))
            leap = datetime(2024, 2, 29, tzinfo=timezone.utc)
            self.assertEqual(dates.next_anniversary(leap, "UTC"), datetime(2027, 2, 28, tzinfo=timezone.utc))
            today = datetime(2026, 11, 3, tzinfo=timezone.utc)
            self.assertEqual(dates.next_anniversary(today, "UTC"), today)
            self.assertEqual(dates.next_anniversary(today, "Asia/Beirut"), datetime(2027, 11, 3, tzinfo=timezone.utc))
            self.assertEqual(dates.days_until(datetime(2026, 11, 10, tzinfo=timezone.utc), "Asia/Beirut"), 6)
            self.assertEqual(dates.add_days_date_only(today, 30), today + timedelta(days=30))
            self.assertEqual(dates.format_date_only(today), "2026-11-03")


if __name__ == "__main__":
    unittest.main()
